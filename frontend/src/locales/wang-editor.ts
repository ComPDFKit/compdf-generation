type CustomLocale = keyof typeof customResources
type SupportedLocale = CustomLocale | 'zh-CN' | 'en'

let resourcesRegistered = false

function registerCustomResources() {
  if (resourcesRegistered) return
  for (const [locale, resources] of Object.entries(customResources)) {
    i18nAddResources(locale, resources)
  }
  resourcesRegistered = true
}

export function changeWangEditorLanguage(locale: string) {
  registerCustomResources()
  const language: SupportedLocale = locale in customResources || locale === 'zh-CN' ? locale as SupportedLocale : 'en'
  i18nChangeLanguage(language)
}
